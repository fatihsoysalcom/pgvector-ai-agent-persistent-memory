import os
import psycopg2
from pgvector.psycopg2 import register_vector

# --- Configuration ---
# Set these environment variables or modify directly
DB_NAME = os.getenv("PG_DB", "your_database_name")
DB_USER = os.getenv("PG_USER", "your_username")
DB_PASSWORD = os.getenv("PG_PASSWORD", "your_password")
DB_HOST = os.getenv("PG_HOST", "localhost")
DB_PORT = os.getenv("PG_PORT", "5432")

# --- Helper function to connect ---
def get_db_connection():
    conn = psycopg2.connect(
        dbname=DB_NAME,
        user=DB_USER,
        password=DB_PASSWORD,
        host=DB_HOST,
        port=DB_PORT
    )
    # Register the vector type with psycopg2 for seamless Python list <-> pgvector conversion
    register_vector(conn)
    return conn

# --- Main logic ---
def main():
    conn = None
    try:
        conn = get_db_connection()
        cur = conn.cursor()

        # 1. Ensure pgvector extension is enabled in your PostgreSQL database.
        #    (Run `CREATE EXTENSION vector;` in your database if not already done.)

        # 2. Create table for AI agent memories if it doesn't exist.
        #    The 'embedding' column uses the 'VECTOR' type provided by pgvector,
        #    here with a dimension of 3 for simplicity.
        cur.execute("""
            CREATE TABLE IF NOT EXISTS agent_memories (
                id SERIAL PRIMARY KEY,
                content TEXT NOT NULL,
                embedding VECTOR(3) NOT NULL
            );
        """)
        conn.commit()
        print("Table 'agent_memories' ensured to exist.")

        # 3. Simulate some AI agent "memories" (Sherlock Strokes) and their embeddings.
        #    In a real application, these embeddings would be generated by an LLM or embedding model.
        memories = [
            ("I learned that the user prefers coffee over tea.", [0.1, 0.2, 0.3]),
            ("The user asked about the weather in Istanbul.", [0.4, 0.5, 0.6]),
            ("I helped the user book a flight to Ankara.", [0.7, 0.8, 0.9]),
            ("The user mentioned their favorite color is blue.", [0.15, 0.25, 0.35]),
            ("I reminded the user about their meeting at 2 PM.", [0.65, 0.75, 0.85]),
        ]

        # 4. Insert memories into the database.
        #    We check for existing content to avoid duplicates on repeated runs.
        for content, embedding in memories:
            cur.execute("SELECT id FROM agent_memories WHERE content = %s", (content,))
            if not cur.fetchone():
                cur.execute(
                    "INSERT INTO agent_memories (content, embedding) VALUES (%s, %s)",
                    (content, embedding)
                )
                print(f"Inserted memory: '{content}'")
        conn.commit()

        # 5. Simulate a new "Sherlock Stroke" (query) and its embedding.
        #    This represents a new piece of information the AI agent receives.
        new_input_embedding = [0.12, 0.22, 0.32] # This embedding is semantically close to the coffee preference memory.

        print(f"\nSearching for memories similar to new input embedding: {new_input_embedding}")

        # 6. Perform a similarity search using pgvector's L2 distance operator (<=>).
        #    The `ORDER BY embedding <=> %s` clause sorts results by their distance
        #    to the `new_input_embedding`, with the closest (smallest distance) first.
        cur.execute(
            "SELECT content, embedding FROM agent_memories ORDER BY embedding <=> %s LIMIT 3",
            (new_input_embedding,)
        )
        similar_memories = cur.fetchall()

        print("\nTop 3 most similar memories (Sherlock Strokes) retrieved:")
        for content, embedding in similar_memories:
            print(f"- Content: '{content}', Embedding: {embedding}")

    except Exception as e:
        print(f"An error occurred: {e}")
    finally:
        if conn:
            conn.close()
            print("\nDatabase connection closed.")

if __name__ == "__main__":
    main()
